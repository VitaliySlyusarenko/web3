@app.route("/check-date", methods=["POST"])
def check_date():

    data = request.get_json(silent=True)

    if not data:

        return jsonify({
            "success": False,
            "message": "Немає даних."
        }), 400


    entered_date = str(
        data.get("date", "")
    ).strip().lower()


    # Дозволені варіанти написання дати

    allowed_dates = {
        "15.02.2005",
        "15.02.2005",
        "15/02/2005",
        "15/02/2005",
        "15 02 2005",
        "15.2.2005",
        "15.02.05",
        "15/02/2002"
    }


    if entered_date in allowed_dates:

        return jsonify({
            "success": True
        })


    return jsonify({
        "success": False,
        "message": "Хммм... Схоже, дата не та 😏"
    })


